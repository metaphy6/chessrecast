  /// Get position value for a piece
  static int getPositionValue(
    PieceType type,
    Position position,
    PieceColor color,
    bool isEndgame,
  ) {
    // Convert position to table index (0-63)
    // For white: row 0 = index 0-7, row 7 = index 56-63
    // For black: flip the board vertically
    final row = color == PieceColor.white ? position.row : 7 - position.row;
    final index = row * 8 + position.col;

    switch (type) {
      case PieceType.pawn:
        return pawnTable[index];
      case PieceType.knight:
        return knightTable[index];
      case PieceType.bishop:
        return bishopTable[index];
      case PieceType.rook:
        return rookTable[index];
      case PieceType.queen:
        return queenTable[index];
      case PieceType.king:
        return isEndgame ? kingEndgameTable[index] : kingMiddlegameTable[index];
    }
  }
